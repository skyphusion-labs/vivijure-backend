#!/usr/bin/env python3
"""Regenerate src/vivijure_backend/harness/stills_manifest.json from the Hugging Face tree API.

Edit FILES when a loader starts opening a different file. Revisions come from
deploy/bake-manifest.json, so this cannot pin a second set. Reads only public metadata.
"""
import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = {  # hydrate order: what every SDXL job reads comes first
    "models--SG161222--RealVisXL_V5.0": [
        "unet/diffusion_pytorch_model-00001-of-00002.safetensors",
        "unet/diffusion_pytorch_model-00002-of-00002.safetensors",
        "vae/diffusion_pytorch_model.safetensors",
        "text_encoder/model.safetensors",
        "text_encoder_2/model.safetensors",
    ],
    "models--xinsir--controlnet-openpose-sdxl-1.0": ["diffusion_pytorch_model.safetensors"],
    "models--ByteDance--Hyper-SD": ["Hyper-SDXL-8steps-lora.safetensors"],
    "models--h94--IP-Adapter": [
        "sdxl_models/ip-adapter_sdxl.safetensors",
        "sdxl_models/image_encoder/model.safetensors",
    ],
    "models--xinsir--controlnet-canny-sdxl-1.0": ["diffusion_pytorch_model.safetensors"],
    "models--InstantX--InstantID": ["ip-adapter.bin"],
}


def main() -> None:
    revs = {r["repo"]: r["rev"] for r in json.loads((ROOT / "deploy/bake-manifest.json").read_text())["keep_repos"]}
    repos = []
    for d, paths in FILES.items():
        repo_id = d[len("models--"):].replace("--", "/")
        url = f"https://huggingface.co/api/models/{repo_id}/tree/{revs[d]}?recursive=true&expand=false"
        tree = {x["path"]: x for x in json.load(urllib.request.urlopen(url, timeout=60)) if x["type"] == "file"}
        repos.append({"dir": d, "repo_id": repo_id, "revision": revs[d], "files": [
            {"path": p, "blob": tree[p]["lfs"]["oid"], "bytes": tree[p]["lfs"]["size"]} for p in paths]})
    out = ROOT / "src/vivijure_backend/harness/stills_manifest.json"
    out.write_text(json.dumps({"_comment": "Generated by scripts/gen_stills_manifest.py. Do not edit by hand.",
                               "repos": repos}, indent=1) + "\n")


if __name__ == "__main__":
    main()
